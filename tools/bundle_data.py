#!/usr/bin/env python3
"""Bundle shared-data JSON into one ES module.

The prototype is a single static page, so inlining the content avoids a fetch
round-trip per file and makes the page work from any origin. The Godot project
reads the same JSON files directly; this is only a packaging step.
"""
import json, io, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SD = ROOT / 'shared-data'

def load(rel):
    return json.loads((SD / rel).read_text(encoding='utf-8'))

bundle = {
    'atlas': load('theaters.json'),
    'chapters': load('chapters.json'),
    'weapons': load('weapons.json'),
    'history': load('historical-records.json'),
    'districts': {},
    'locales': {},
}
for p in sorted((SD / 'districts').glob('*.json')):
    d = json.loads(p.read_text(encoding='utf-8'))
    bundle['districts'][d['id']] = d
for p in sorted((SD / 'locales').glob('*.json')):
    bundle['locales'][p.stem] = json.loads(p.read_text(encoding='utf-8'))

out = ROOT / 'web' / 'src' / 'data.generated.js'
parts = ['// GENERATED by tools/bundle_data.py — do not edit. Source of truth: shared-data/*.json\n']
for k, v in bundle.items():
    parts.append(f'export const {k} = ' + json.dumps(v, ensure_ascii=False, separators=(',', ':')) + ';\n')
parts.append("""
export const content = { ...chapters, districts };
export const CONTENT_VERSIONS = Object.fromEntries(Object.values(districts).map((d) => [d.id, d.content_version]));
""")
out.write_text(''.join(parts), encoding='utf-8')
kb = out.stat().st_size / 1024
print(f'wrote {out.relative_to(ROOT)} ({kb:.0f} KB): '
      f"{len(bundle['districts'])} districts, {len(bundle['locales'])} locales, "
      f"{len(bundle['chapters']['chapters'])} chapters, {len(bundle['weapons']['weapons'])} weapons")
